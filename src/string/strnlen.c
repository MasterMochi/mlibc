/* 標準ヘッダ */
#include <stddef.h>
#include <string.h>


/******************************************************************************/
/* グローバル関数宣言                                                         */
/******************************************************************************/
/******************************************************************************/
/**
 * @brief       strnlen
 * @details     文字列の文字数を返す。
 *
 * @param[in]   *s     文字列
 * @param[in]   maxlen 最大文字数
 *
 * @return      文字数
 *
 * @note        null文字はカウントされない。
 */
/******************************************************************************/
size_t strnlen( const char *s,
                size_t     maxlen )
{
    size_t ret;

    /* 初期化 */
    ret = 0;

    /* null文字まで繰り返し */
    while ( ( *s != '\0' ) && ( maxlen > 0 ) ) {
        /* 文字数加算 */
        ret++;

        /* アドレス更新 */
        s++;
        maxlen--;
    }

    return ret;
}


