/**
 * @brief       llabs
 * @details     絶対値を返す。
 *
 * @param[in]   j 値
 *
 * @return      絶対値を返す。
 */
/******************************************************************************/
long long int llabs( long long int j )
{
    /* 符号判定 */
    if ( j < 0 ) {
        /* - */

        /* 符号反転 */
        j *= -1;
    }

    return j;
}


